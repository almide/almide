use std::{fs, io};
use std::path::Path;

// ONE stripper, shared verbatim with the compiler's emit path (#2511). The two copies
// used to count braces per line with no notion of a string literal, so an unbalanced
// brace inside one (`r"a\{x"`) lost the block's end and deleted to EOF. Shared the same
// way `fusion_parse.rs` is shared with almide-egg-lab's build script: a `#[path]` module,
// so the file is compiled into both the build script and the library and cannot drift.
#[path = "../src/strip_test_blocks.rs"]
mod strip_test_blocks;
use self::strip_test_blocks::strip_test_blocks;

/// Run the stripper for its verdict only, and turn a lost block end into a BUILD failure
/// naming the file. The runtime modules are embedded unstripped and stripped at emit, so
/// this is the earliest point the defect can be caught — and a build error is the loud
/// version of what used to be a silent tail deletion. For a module assembled from
/// `include!` parts the reported line is the line in the assembled text.
fn reject_unterminated_test_block(path: &Path, content: &str) -> io::Result<()> {
    strip_test_blocks(content, &path.display().to_string())
        .map(|_| ())
        .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e.to_string()))
}

/// Read a runtime source file, INLINING any `include!("X.rs")` directive with the
/// referenced file's content (resolved relative to this file's directory), recursively.
/// The runtime is embedded as ONE source string per module and assembled by
/// concatenation — it does not ship the sibling part files — so an `include!` (used to
/// keep each on-disk file under the 1000-line limit) must be resolved at embed time, or
/// it dangles in the generated crate (`couldn't read X.rs`).
fn read_with_includes(path: &Path) -> io::Result<String> {
    let content = read_source(path)?;
    let dir = path.parent().ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, format!("source has no parent: {}", path.display())))?;
    let mut out = String::new();
    for line in content.lines() {
        let t = line.trim();
        let inc_name = t
            .strip_prefix("include!(\"")
            .and_then(|r| r.strip_suffix("\");").or_else(|| r.strip_suffix("\")")));
        if let Some(fname) = inc_name {
            out.push_str(&read_with_includes(&dir.join(fname))?);
            out.push('\n');
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(out)
}

/// File names that are `include!`d by another file (the split "part" files). They are
/// inlined into their parent's embedded source by [`read_with_includes`], so they must
/// NOT also be emitted as their own top-level runtime module entry.
fn included_part_names(entries: &[fs::DirEntry]) -> io::Result<std::collections::HashSet<String>> {
    let mut parts = std::collections::HashSet::new();
    for e in entries {
        let content = read_source(&e.path())?;
        for line in content.lines() {
            let t = line.trim();
            if let Some(fname) = t
                .strip_prefix("include!(\"")
                .and_then(|r| r.strip_suffix("\");").or_else(|| r.strip_suffix("\")")))
            {
                parts.insert(fname.to_string());
            }
        }
    }
    Ok(parts)
}

pub fn generate(workspace_root: &Path, out_dir: &Path) -> io::Result<()> {
    let rust_dir = workspace_root.join("runtime/rs/src");
    if !rust_dir.exists() {
        return Ok(());
    }

    let mut rust_entries: Vec<_> = fs::read_dir(&rust_dir)?
        .collect::<io::Result<Vec<_>>>()?
        .into_iter()
        .filter(|e| e.path().extension().is_some_and(|ext| ext == "rs"))
        .filter(|e| e.file_name() != "lib.rs")
        .collect();
    rust_entries.sort_by_key(|e| e.file_name());
    // Drop the split "part" files — their content is inlined into their parent module's
    // embedded string (see read_with_includes), so they are not standalone modules.
    let parts = included_part_names(&rust_entries)?;
    rust_entries.retain(|e| !e.file_name().to_str().is_some_and(|name| parts.contains(name)));

    let mut rust_out = String::new();
    rust_out.push_str("// AUTO-GENERATED by build.rs from runtime/rs/src/ — DO NOT EDIT\n\n");
    rust_out.push_str("pub const RUST_RUNTIME_MODULES: &[(&str, &str)] = &[\n");
    for entry in &rust_entries {
        let stem = module_name(&entry.path())?;
        let content = read_with_includes(&entry.path())?;
        reject_unterminated_test_block(&entry.path(), &content)?;
        rust_out.push_str(&format!("    (\"{stem}\", {content:?}),\n"));
    }
    rust_out.push_str("];\n\n");

    // Auto-extract inter-module dependencies by scanning each module's
    // source for `almide_rt_{other}_` references. No manual whitelist.
    let module_names: Vec<String> = rust_entries.iter().map(|e| {
        module_name(&e.path())
    }).collect::<io::Result<_>>()?;

    // The `Almide*` types each module defines at top level: a module that
    // names one (json.rs's `AlmideMap` in `almide_json_to_map`) depends on its
    // definer as surely as on an `almide_rt_` fn. Before #4071 `map` was in
    // every program, so the type edge never had to be stated.
    let mut defined_types: Vec<(String, Vec<String>)> = Vec::new();
    for entry in &rust_entries {
        let stem = module_name(&entry.path())?;
        let content = read_with_includes(&entry.path())?;
        defined_types.push((stem, top_level_almide_types(&content)));
    }

    rust_out.push_str("/// Inter-module runtime dependencies, auto-extracted from source.\n");
    rust_out.push_str("/// If module A's source references `almide_rt_B_*`, or names an `Almide*`\n");
    rust_out.push_str("/// type B defines at top level, A depends on B.\n");
    rust_out.push_str("pub const RUNTIME_DEPS: &[(&str, &[&str])] = &[\n");
    for entry in &rust_entries {
        let stem = module_name(&entry.path())?;
        let content = read_with_includes(&entry.path())?;
        let mut deps: Vec<&str> = Vec::new();
        for other in &module_names {
            if *other == stem { continue; }
            let prefix = format!("almide_rt_{}_", other);
            let names_a_type = defined_types
                .iter()
                .find(|(m, _)| m == other)
                .is_some_and(|(_, tys)| tys.iter().any(|t| contains_ident(&content, t)));
            if content.contains(&prefix) || names_a_type {
                deps.push(other);
            }
        }
        if !deps.is_empty() {
            rust_out.push_str(&format!("    (\"{}\", &[{}]),\n", stem,
                deps.iter().map(|d| format!("\"{}\"", d)).collect::<Vec<_>>().join(", ")));
        }
    }
    rust_out.push_str("];\n");

    rust_out.push_str("\n/// almide-kernel embedded as an inlinable `mod almide_kernel`, dropped into the\n");
    rust_out.push_str("/// runtime source wherever the `matrix` module is used (see emit_runtime_crate).\n");
    let kernel_inline = build_kernel_inline(workspace_root)?;
    rust_out.push_str(&format!("pub const ALMIDE_KERNEL_INLINE: &str = {kernel_inline:?};\n"));

    fs::write(out_dir.join("rust_runtime.rs"), &rust_out)?;

    write_runtime_fn_modes(&rust_entries, out_dir)?;

    println!("cargo:rerun-if-changed={}", rust_dir.display());
    // The shared runtime cores (#1715): runtime/rs modules `include!` files
    // from this crate (http.rs -> http_client_core.rs), and the resolver
    // above inlines them — so an edit there must re-embed too, or the
    // committed rust_runtime.rs silently desyncs (the #419 class).
    println!(
        "cargo:rerun-if-changed={}",
        workspace_root.join("crates/almide-rt-core/src").display()
    );
    // fs.rs splices almide-base's classified errno rows (C-273) the same way.
    println!(
        "cargo:rerun-if-changed={}",
        workspace_root.join("crates/almide-base/src/fs_errno_classified.rs").display()
    );
    Ok(())
}

/// Embed the almide-kernel crate as an inlinable `mod almide_kernel`.
/// `runtime/rs/src/matrix.rs` calls `almide_kernel::…` for the SIMD hot
/// paths, but the `almide test`/`almide build` fast paths compile the
/// runtime as a single crate (rlib or inlined) with no `almide_kernel`
/// extern — so matrix specs failed to resolve the crate. Embed the kernel
/// source so emit_runtime_crate / emit_source can drop it in as a
/// crate-local module wherever `matrix` is used; no extern, no rlib
/// plumbing, and the cargo path gets it for free too.
///
/// Kernel modules reference siblings via `crate::silu` etc.; wrapped one
/// level deep under `mod almide_kernel`, that sibling path is
/// `super::silu`, so rewrite `crate::` → `super::`. Test blocks are
/// stripped — the runtime is built with `--test`, so the kernel's own
/// `#[cfg(test)]` would otherwise run inside every spec. Extracted from
/// `generate` (cog>25 decomposition).
/// The `Almide*` names a runtime source defines at the start of a line
/// (`pub struct` / `pub enum` / `pub type` / `pub trait`).
fn top_level_almide_types(content: &str) -> Vec<String> {
    content
        .lines()
        .filter_map(|line| {
            let rest = ["pub struct ", "pub enum ", "pub type ", "pub trait "]
                .iter()
                .find_map(|kw| line.strip_prefix(kw))?;
            let end = rest.find(|c: char| !(c == '_' || c.is_ascii_alphanumeric())).unwrap_or(rest.len());
            let name = &rest[..end];
            name.starts_with("Almide").then(|| name.to_string())
        })
        .collect()
}

/// Whether `content`'s CODE (`//` comments dropped — a doc line mentioning
/// another module's type is not a use of it) contains `name` as a whole
/// identifier (not a prefix of a longer one: `AlmideMapKey` is not
/// `AlmideMap`).
fn contains_ident(content: &str, name: &str) -> bool {
    let is_ident = |c: char| c == '_' || c.is_ascii_alphanumeric();
    content.lines().map(strip_line_comment).any(|line| {
        line.match_indices(name).any(|(i, _)| {
            let before = line[..i].chars().next_back();
            let after = line[i + name.len()..].chars().next();
            !before.is_some_and(is_ident) && !after.is_some_and(is_ident)
        })
    })
}

/// `line` up to its `//` comment, a `//` inside a `"…"` literal kept.
fn strip_line_comment(line: &str) -> &str {
    let bytes = line.as_bytes();
    let mut in_str = false;
    let mut i = 0;
    while i < bytes.len() {
        match bytes[i] {
            b'\\' if in_str => i += 1,
            b'"' => in_str = !in_str,
            b'/' if !in_str && bytes.get(i + 1) == Some(&b'/') => return &line[..i],
            _ => {}
        }
        i += 1;
    }
    line
}

fn build_kernel_inline(workspace_root: &Path) -> io::Result<String> {
    let kernel_dir = workspace_root.join("crates/almide-kernel/src");
    if !kernel_dir.exists() {
        return Ok(String::new());
    }
    let lib = read_source(&kernel_dir.join("lib.rs"))?;
    let mut mods: Vec<String> = lib
        .lines()
        .filter_map(|l| l.trim().strip_prefix("pub mod ").and_then(|s| s.strip_suffix(';')))
        .map(|s| s.trim().to_string())
        .collect();
    mods.sort();
    let mut inline = String::new();
    inline.push_str("#[allow(dead_code, unused_imports, unused_variables, unused_parens, unused_mut, non_snake_case, clippy::all)]\nmod almide_kernel {\n");
    for m in &mods {
        // `bridge` is the kernel's STANDALONE bench/ABI-glue module, written against
        // the pre-0.28 nested `Vec<Vec<f64>>` matrix; nothing in the runtime calls
        // `bridge::` (matrix.rs calls the kernels directly on the flat struct).
        // Embedding it shipped a second, stale `AlmideMatrix` into every generated
        // matrix crate — and its alias line was the exact marker the old burn
        // splicer keyed on, so the splicer fired INSIDE the bridge and produced
        // invalid Rust (#739). Kernel compute modules only.
        if m == "bridge" {
            continue;
        }
        {
            let path = kernel_dir.join(format!("{m}.rs"));
            let src = read_source(&path)?;
            let body = strip_test_blocks(&src, &path.display().to_string())
                .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e.to_string()))?
                .replace("crate::", "super::");
            inline.push_str(&format!("pub mod {m} {{\n{body}\n}}\n"));
        }
    }
    inline.push_str("}\n");
    println!("cargo:rerun-if-changed={}", kernel_dir.display());
    Ok(inline)
}

/// Auto-extract the runtime helpers whose LAST positional parameter is a
/// generic `F: Fn(...)` element fn (the value codec combinators —
/// encode/decode list, option, …), and write `runtime_fn_modes.rs`. Their
/// fn argument must stay a raw `impl Fn`, NOT the uniform `Rc<dyn Fn>`
/// closure value. Derived from the signatures themselves (no
/// hand-maintained allow-list) so a new codec combinator needs no codegen
/// edit. Extracted from `generate` (cog>25 decomposition).
fn write_runtime_fn_modes(rust_entries: &[fs::DirEntry], out_dir: &Path) -> io::Result<()> {
    let mut raw_fn_helpers: Vec<String> = Vec::new();
    let mut mut_params: Vec<(String, Vec<bool>)> = Vec::new();
    let mut generics: Vec<(String, String)> = Vec::new();
    for entry in rust_entries {
        let content = read_with_includes(&entry.path())?;
        raw_fn_helpers.extend(extract_raw_fn_last_arg_helpers(&content));
        mut_params.extend(extract_runtime_param_mutability(&content));
        generics.extend(extract_runtime_generics(&content));
    }
    let mut twins = send_twins(&generics);
    twins.sort();
    twins.dedup();
    raw_fn_helpers.sort();
    raw_fn_helpers.dedup();
    mut_params.sort();
    mut_params.dedup();

    let mut modes_out = String::new();
    modes_out.push_str("// AUTO-GENERATED by build.rs from runtime/rs/src/ — DO NOT EDIT\n\n");
    modes_out.push_str("/// Runtime helpers whose LAST positional argument is a generic `F: Fn(...)`\n");
    modes_out.push_str("/// element fn (value codec combinators) — extracted from the signatures.\n");
    modes_out.push_str("pub fn takes_raw_fn_last_arg(name: &str) -> bool {\n");
    if raw_fn_helpers.is_empty() {
        modes_out.push_str("    let _ = name;\n    false\n");
    } else {
        modes_out.push_str("    matches!(name,\n");
        for (i, h) in raw_fn_helpers.iter().enumerate() {
            let sep = if i + 1 < raw_fn_helpers.len() { " |" } else { "" };
            modes_out.push_str(&format!("        \"{}\"{}\n", h, sep));
        }
        modes_out.push_str("    )\n");
    }
    modes_out.push_str("}\n");

    modes_out.push_str("\n/// Per-parameter `&mut` mode of a native runtime helper, keyed by its\n");
    modes_out.push_str("/// `almide_rt_*` symbol — extracted from `runtime/rs/src/` signatures.\n");
    modes_out.push_str("/// `None` means the symbol has no native runtime body (wasm-only prims,\n");
    modes_out.push_str("/// `@intrinsic`s served by a self-hosted implementation), so callers must\n");
    modes_out.push_str("/// fall back to signature-shape inference rather than assuming immutable.\n");
    modes_out.push_str("pub fn runtime_param_mutability(name: &str) -> Option<&'static [bool]> {\n");
    if mut_params.is_empty() {
        modes_out.push_str("    let _ = name;\n    None\n");
    } else {
        modes_out.push_str("    Some(match name {\n");
        for (n, modes) in &mut_params {
            let list = modes.iter().map(|m| m.to_string()).collect::<Vec<_>>().join(", ");
            modes_out.push_str(&format!("        \"{}\" => &[{}],\n", n, list));
        }
        modes_out.push_str("        _ => return None,\n");
        modes_out.push_str("    })\n");
    }
    modes_out.push_str("}\n");

    modes_out.push_str("\n/// The `Send`-free `_seq` twin of a threaded runtime helper (#3649) —\n");
    modes_out.push_str("/// paired from the signatures: the helper has a `Send` bound, the twin none.\n");
    modes_out.push_str("pub fn send_free_twin(name: &str) -> Option<&'static str> {\n");
    modes_out.push_str("    match name {\n");
    for (threaded, twin) in &twins {
        modes_out.push_str(&format!("        \"{}\" => Some(\"{}\"),\n", threaded, twin));
    }
    modes_out.push_str("        _ => None,\n    }\n}\n");
    let mut crossing: Vec<&String> = generics.iter().filter(|(_, g)| g.contains("Send")).map(|(n, _)| n).collect();
    crossing.sort();
    crossing.dedup();
    modes_out.push_str("\n/// The runtime helpers that hand work to scoped threads: their signature\n");
    modes_out.push_str("/// bounds `Send` (ADR-0013 marks what they capture thread-shared).\n");
    modes_out.push_str("pub fn crosses_threads(name: &str) -> bool {\n    matches!(name,\n");
    for (i, n) in crossing.iter().enumerate() {
        let sep = if i + 1 < crossing.len() { " |" } else { "" };
        modes_out.push_str(&format!("        \"{}\"{}\n", n, sep));
    }
    modes_out.push_str("    )\n}\n");
    fs::write(out_dir.join("runtime_fn_modes.rs"), &modes_out)
}

/// Per-parameter `&mut`-ness of every `pub fn almide_rt_*` in the native
/// runtime, derived from the signature itself.
///
/// This is the GROUND TRUTH for `BorrowInferencePass`'s intrinsic seeding.
/// Before it existed, an `@intrinsic` fn returning `Unit` was ASSUMED to
/// mutate its first heap argument in place, which emitted `&mut x` against
/// read-only helpers like `almide_rt_io___write_stdout(data: &Vec<u8>)` → E0596 in
/// generated Rust (#803). A generic parameter (`x: T`) is not a reference at
/// all, so it records `false`.
fn extract_runtime_param_mutability(content: &str) -> Vec<(String, Vec<bool>)> {
    let mut out = Vec::new();
    let mut cursor = 0;
    while let Some(rel) = content[cursor..].find("pub fn ") {
        let name_start = cursor + rel + "pub fn ".len();
        let name_end = content[name_start..]
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .map(|i| name_start + i)
            .unwrap_or(content.len());
        let name = content[name_start..name_end].to_string();
        cursor = name_end;
        if !name.starts_with("almide_rt_") {
            continue;
        }
        let rest = content[name_end..].trim_start();
        // Skip an optional `<generics>` clause before the parameter list.
        let after = if rest.starts_with('<') {
            match balanced(rest, '<', '>') {
                Some(end) => rest[end + 1..].trim_start(),
                None => continue,
            }
        } else {
            rest
        };
        if !after.starts_with('(') {
            continue;
        }
        let Some(end) = balanced(after, '(', ')') else { continue };
        let modes: Vec<bool> = split_top_level(&after[1..end])
            .into_iter()
            .filter_map(|p| {
                let colon = p.find(':')?;
                Some(p[colon + 1..].trim_start().starts_with("&mut "))
            })
            .collect();
        out.push((name, modes));
    }
    out
}

/// The generic clause of every `pub fn almide_rt_*` (empty when it has none),
/// keyed by name — the input `send_twins` pairs threaded helpers from.
fn extract_runtime_generics(content: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut cursor = 0;
    while let Some(rel) = content[cursor..].find("pub fn almide_rt_") {
        let name_start = cursor + rel + "pub fn ".len();
        let name_end = content[name_start..]
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .map_or(content.len(), |i| name_start + i);
        cursor = name_end;
        let rest = &content[name_end..];
        let generics = if rest.starts_with('<') {
            balanced(rest, '<', '>').map_or("", |end| &rest[..=end])
        } else {
            ""
        };
        out.push((content[name_start..name_end].to_string(), generics.to_string()));
    }
    out
}

/// #3649: a runtime helper with a `Send` bound runs its work on threads, so a
/// value holding an `Rc` cannot reach it. Its twin is the same name with a
/// `_seq` suffix and no `Send` bound; RustLowering routes such a value there.
/// Pairs `(threaded, twin)`, derived from the signatures alone.
fn send_twins(generics: &[(String, String)]) -> Vec<(String, String)> {
    generics
        .iter()
        .filter(|(_, g)| g.contains("Send"))
        .filter_map(|(name, _)| {
            let twin = format!("{name}_seq");
            generics
                .iter()
                .any(|(n, g)| *n == twin && !g.contains("Send"))
                .then(|| (name.clone(), twin))
        })
        .collect()
}

/// Names of `pub fn`s whose declared generics include a `<G>: Fn(...)` bound and
/// whose LAST positional parameter has type exactly that generic `G`. These take a
/// raw `impl Fn` (monomorphized), not a `Rc<dyn Fn>` closure value.
fn extract_raw_fn_last_arg_helpers(content: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cursor = 0;
    while let Some(rel) = content[cursor..].find("pub fn ") {
        let (new_cursor, matched) = try_raw_fn_last_arg_helper_at(content, cursor, rel);
        cursor = new_cursor;
        if let Some(name) = matched {
            out.push(name);
        }
    }
    out
}

/// One `while` iteration of `extract_raw_fn_last_arg_helpers`, extracted
/// (cog>30 decomposition). The original's mid-loop `continue`s only ever
/// skipped pushing to `out` for THIS `pub fn` — `cursor` was already
/// advanced past its name before any of them — so this helper returns
/// `(new_cursor, Option<matched_name>)` instead: same "advance, maybe
/// record" shape, not an early-exit-the-whole-function hazard.
fn try_raw_fn_last_arg_helper_at(content: &str, cursor: usize, rel: usize) -> (usize, Option<String>) {
    let name_start = cursor + rel + "pub fn ".len();
    let name_end = content[name_start..]
        .find(|c: char| !(c.is_alphanumeric() || c == '_'))
        .map(|i| name_start + i)
        .unwrap_or(content.len());
    let name = content[name_start..name_end].to_string();
    let new_cursor = name_end;

    let rest = content[name_end..].trim_start();
    // Optional `<generics>` then `(params)`.
    let (generics, after) = if rest.starts_with('<') {
        match balanced(rest, '<', '>') {
            Some(end) => (&rest[1..end], rest[end + 1..].trim_start()),
            None => return (new_cursor, None),
        }
    } else {
        ("", rest)
    };
    if !after.starts_with('(') {
        return (new_cursor, None);
    }
    let params = match balanced(after, '(', ')') {
        Some(end) => &after[1..end],
        None => return (new_cursor, None),
    };

    // Generics with a `Fn` bound: `F: Fn(...) -> _`.
    let fn_generics: Vec<&str> = split_top_level(generics)
        .into_iter()
        .filter_map(|g| {
            let g = g.trim();
            let colon = g.find(':')?;
            if g[colon + 1..].trim_start().starts_with("Fn") {
                Some(g[..colon].trim())
            } else {
                None
            }
        })
        .collect();
    if fn_generics.is_empty() {
        return (new_cursor, None);
    }

    // Last param's type is exactly one of those Fn generics.
    if let Some(last) = split_top_level(params).last()
        && let Some(colon) = last.rfind(':')
    {
        let ty = last[colon + 1..].trim();
        if fn_generics.contains(&ty) {
            return (new_cursor, Some(name));
        }
    }
    (new_cursor, None)
}

/// Index of the close delimiter matching the open at `s[0]` (`s` must start with
/// `open`), honoring nesting. The `>` in a `->` return arrow is NOT a closing angle
/// bracket (e.g. `<F: Fn(T) -> Value>`). Returns None if unbalanced.
fn balanced(s: &str, open: char, close: char) -> Option<usize> {
    let mut depth = 0i32;
    let mut prev = ' ';
    for (i, c) in s.char_indices() {
        if c == close && close == '>' && prev == '-' {
            prev = c;
            continue;
        }
        if c == open {
            depth += 1;
        } else if c == close {
            depth -= 1;
            if depth == 0 {
                return Some(i);
            }
        }
        prev = c;
    }
    None
}

/// Split by top-level commas, ignoring commas nested in `<>`, `()`, or `[]`. The
/// `>` in a `->` return arrow does not close an angle bracket.
fn split_top_level(s: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut depth = 0i32;
    let mut start = 0;
    let mut prev = ' ';
    for (i, c) in s.char_indices() {
        match c {
            '<' | '(' | '[' => depth += 1,
            '>' if prev == '-' => {}
            '>' | ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                parts.push(&s[start..i]);
                start = i + 1;
            }
            _ => {}
        }
        prev = c;
    }
    if !s[start..].trim().is_empty() {
        parts.push(&s[start..]);
    }
    parts
}

fn read_source(path: &Path) -> io::Result<String> {
    fs::read_to_string(path).map_err(|error| io::Error::new(error.kind(), format!("{}: {error}", path.display())))
}

fn module_name(path: &Path) -> io::Result<String> {
    path.file_stem().and_then(|s| s.to_str()).map(str::to_owned)
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, format!("invalid runtime module name: {}", path.display())))
}
