//! Decoding the shipped module: every defined function's instructions, with
//! the control depth and store-address provenance the checks read.

use wasmparser::{FuncToValidate, FunctionBody, Operator as Op, Parser, ValidPayload, Validator, ValidatorResources, WasmFeatures};

/// How an operator moves control, as far as this checker follows it.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Control {
    /// Falls through to the next instruction, or traps.
    Plain,
    /// A control instruction the depth count and `branch_target` follow.
    Modeled,
    /// Transfers control, opens a frame or runs other code in a way this
    /// checker does not follow (#4854): the module is not judged.
    Refused,
}

include!("control_table.rs");

/// The classifier: one arm per `Operator` variant of the wasmparser this
/// crate builds against, generated by `for_each_operator!` and answered by
/// [`control_class!`]'s explicit table, so an operator the table does not
/// name fails to compile instead of passing as one that does not branch.
macro_rules! define_control {
    ($( @$proposal:ident $op:ident $({ $($arg:ident: $argty:ty),* })? => $visit:ident ($($ann:tt)*))*) => {
        fn control(op: &Op<'_>) -> Control {
            #[allow(unreachable_patterns)]
            match op {
                $( Op::$op { .. } => control_class!($op), )*
                // `Operator` is `#[non_exhaustive]`; nothing reaches here at
                // this wasmparser, and anything that did would be unknown.
                _ => Control::Refused,
            }
        }
    };
}
wasmparser::for_each_operator!(define_control);

/// One defined function's instructions, as the checker needs them.
pub struct Body<'a> {
    pub ops: Vec<Op<'a>>,
    /// Control depth before each instruction (0 = the function's own frame).
    pub depth: Vec<u32>,
    /// For a store: the instruction that pushed its address operand, when
    /// the provenance walk knows it.
    pub addr: Vec<Option<usize>>,
    /// For every instruction, the instruction that pushed each operand it
    /// pops, bottom first, when the provenance walk knows it (operands.rs
    /// rebuilds a value's expression from these).
    pub args: Vec<Vec<Option<usize>>>,
}

/// The proposals whose control flow this checker does not classify (#4854):
/// GC's `br_on_cast*`, the legacy exception handling's `try` / `delegate`,
/// stack switching's `resume` / `switch`. A module using any of them is
/// REFUSED by validation rather than read as if those operators did not
/// branch — the checker's domain is declared here, not defaulted. The
/// operators of the proposals it does validate but does not follow
/// (`try_table`, `throw`, `br_on_null`, `call_ref`, ...) are refused per
/// operator by the control table, naming the instruction.
pub(crate) const UNCLASSIFIED_PROPOSALS: WasmFeatures =
    WasmFeatures::GC.union(WasmFeatures::LEGACY_EXCEPTIONS).union(WasmFeatures::STACK_SWITCHING);

/// Every defined function of `bytes`, validated, in position order.
pub fn decode(bytes: &[u8]) -> Result<Vec<Body<'_>>, String> {
    // Every proposal but the unclassified ones (#4854) and the threads ones:
    // no check follows an atomic access (a store of a block's count word
    // among them), so a module that holds one does not validate here and is
    // not judged.
    let followed = WasmFeatures::all()
        - UNCLASSIFIED_PROPOSALS
        - WasmFeatures::THREADS
        - WasmFeatures::SHARED_EVERYTHING_THREADS;
    let mut v = Validator::new_with_features(followed);
    let mut out = Vec::new();
    let mut memories = 0u32;
    for payload in Parser::new(0).parse_all(bytes) {
        let payload = payload.map_err(|e| e.to_string())?;
        one_plain_memory(&payload, &mut memories)?;
        if let ValidPayload::Func(func, body) = v.payload(&payload).map_err(|e| e.to_string())? {
            out.push(decode_body(func, body)?);
        }
    }
    Ok(out)
}

/// The memories `payload` declares or imports, held to one in the module
/// that is unshared and 32-bit. No check looks at which memory an instruction
/// names: a count read from one memory bounds nothing in another, and a
/// shared memory may be written by another thread between a check and its
/// access. Such a module is not judged.
fn one_plain_memory(payload: &wasmparser::Payload<'_>, seen: &mut u32) -> Result<(), String> {
    let mut found = Vec::new();
    match payload {
        wasmparser::Payload::MemorySection(r) => {
            for m in r.clone() {
                found.push(m.map_err(|e| e.to_string())?);
            }
        }
        wasmparser::Payload::ImportSection(r) => {
            for i in r.clone().into_imports() {
                if let wasmparser::TypeRef::Memory(m) = i.map_err(|e| e.to_string())?.ty {
                    found.push(m);
                }
            }
        }
        _ => {}
    }
    for m in found {
        *seen += 1;
        if *seen > 1 {
            return Err("the module has more than one memory: the checks do not follow which memory an instruction names".into());
        }
        if m.shared {
            return Err("the module's memory is shared: another thread may write it between a check and its access".into());
        }
        if m.memory64 {
            return Err("the module's memory is 64-bit: the checks read 32-bit addresses".into());
        }
    }
    Ok(())
}

/// One defined function's body, validated, with its depths and provenance.
fn decode_body<'a>(func: FuncToValidate<ValidatorResources>, body: FunctionBody<'a>) -> Result<Body<'a>, String> {
    let mut fv = func.into_validator(Default::default());
    let mut br = body.get_binary_reader();
    fv.read_locals(&mut br).map_err(|e| e.to_string())?;
    let mut r = wasmparser::OperatorsReader::new(br);
    let (mut ops, mut depth, mut addr, mut args) = (Vec::new(), Vec::new(), Vec::new(), Vec::new());
    let mut shadow: Vec<Option<usize>> = Vec::new();
    while !r.eof() {
        let off = r.original_position();
        let op = r.read().map_err(|e| e.to_string())?;
        let i = ops.len();
        if control(&op) == Control::Refused {
            return Err(format!("instruction {i} ({op:?}) is a control operator this checker does not follow"));
        }
        // A loop typed by a function type may take parameters, and a branch to
        // it then carries values across its back edge on the operand stack.
        // The checks follow a value across a back edge only through a local,
        // a global or memory, so such a loop is not judged.
        if matches!(op, Op::Loop { blockty: wasmparser::BlockType::FuncType(_) }) {
            return Err(format!("instruction {i} ({op:?}) is a loop typed by a function type: it may take parameters across its back edge"));
        }
        let pre = fv.operand_stack_height() as usize;
        // No instruction of a frame reaches below the frame's own height: past
        // an `unreachable` or a branch its operands are conjured, not the
        // enclosing frame's values (#4599: the `end` of a trapping match arm
        // took the tuple block's address as its own operand).
        let floor = fv.get_control_frame(0).map_or(0, |f| f.height);
        let arity = op.operator_arity(&fv);
        args.push(popped(&shadow, arity, pre, floor));
        addr.push(if store_width(&op).is_some() && pre >= 2 && pre - 2 >= floor {
            shadow.get(pre - 2).copied().flatten()
        } else {
            None
        });
        // The depth is the validator's own control stack (the function's
        // frame not counted), so every block-opening operator counts (#4854).
        let d = fv.control_stack_height().saturating_sub(1);
        depth.push(d);
        fv.op(off, &op).map_err(|e| e.to_string())?;
        let post = fv.operand_stack_height() as usize;
        reshadow(&mut shadow, arity, (pre, post, floor), i);
        ops.push(op);
    }
    Ok(Body { ops, depth, addr, args })
}

/// The producers of the operands an instruction of `arity` pops from a
/// stack of height `pre`, bottom first. An operand below the frame's
/// `floor` is conjured by a polymorphic stack: it has no producer.
fn popped(shadow: &[Option<usize>], arity: Option<(u32, u32)>, pre: usize, floor: usize) -> Vec<Option<usize>> {
    match arity {
        Some((k, _)) if shadow.len() == pre => (0..k as usize)
            .map(|n| (pre + n).checked_sub(k as usize).filter(|j| *j >= floor).and_then(|j| shadow[j]))
            .collect(),
        Some((k, _)) => vec![None; k as usize],
        None => Vec::new(),
    }
}

/// The shadow stack after instruction `i` took it from height `pre` to
/// `post`, inside a frame whose values start at `floor`: what lies below
/// the floor belongs to the enclosing frames and is never this op's.
fn reshadow(shadow: &mut Vec<Option<usize>>, arity: Option<(u32, u32)>, (pre, post, floor): (usize, usize, usize), i: usize) {
    let floor = floor.min(shadow.len()).min(post);
    match arity {
        Some((k, _)) => {
            let keep = pre.saturating_sub(k as usize).max(floor).min(post);
            shadow.truncate(keep);
            // Pushed by this instruction (or, past a polymorphic
            // stack, re-derived by it): its own.
            while shadow.len() < post {
                shadow.push(Some(i));
            }
        }
        None => {
            shadow[floor..].iter_mut().for_each(|s| *s = None);
            shadow.truncate(post);
            while shadow.len() < post {
                shadow.push(None);
            }
        }
    }
}

/// How many functions the module imports (they precede the defined ones in
/// the function index space).
pub fn function_imports(bytes: &[u8]) -> u32 {
    let mut n = 0;
    for payload in Parser::new(0).parse_all(bytes).flatten() {
        if let wasmparser::Payload::ImportSection(r) = payload {
            n += r
                .into_imports()
                .flatten()
                .filter(|i| matches!(i.ty, wasmparser::TypeRef::Func(_)))
                .count() as u32;
        }
    }
    n
}

/// A store's width in bytes and its static offset.
pub fn store_width(op: &Op<'_>) -> Option<(u32, u64)> {
    Some(match op {
        Op::I32Store { memarg } | Op::F32Store { memarg } | Op::I64Store32 { memarg } => {
            (4, memarg.offset)
        }
        Op::I64Store { memarg } | Op::F64Store { memarg } => (8, memarg.offset),
        Op::I32Store8 { memarg } | Op::I64Store8 { memarg } => (1, memarg.offset),
        Op::I32Store16 { memarg } | Op::I64Store16 { memarg } => (2, memarg.offset),
        Op::V128Store { memarg } => (16, memarg.offset),
        _ => return None,
    })
}

pub fn is_load(op: &Op<'_>) -> bool {
    matches!(
        op,
        Op::I32Load { .. }
            | Op::I64Load { .. }
            | Op::F32Load { .. }
            | Op::F64Load { .. }
            | Op::I32Load8S { .. }
            | Op::I32Load8U { .. }
            | Op::I32Load16S { .. }
            | Op::I32Load16U { .. }
            | Op::I64Load8S { .. }
            | Op::I64Load8U { .. }
            | Op::I64Load16S { .. }
            | Op::I64Load16U { .. }
            | Op::I64Load32S { .. }
            | Op::I64Load32U { .. }
            | Op::V128Load { .. }
    )
}

/// Every frame a branch may leave to (see [`branch_target`]): each target of
/// a `br_table`, the one target of any other branch; empty for an
/// instruction that does not branch.
pub(crate) fn branch_targets(op: &Op<'_>, d: u32) -> Vec<u32> {
    match op {
        Op::BrTable { targets } => targets
            .targets()
            .filter_map(Result::ok)
            .chain(std::iter::once(targets.default()))
            .map(|r| d.saturating_sub(r))
            .collect(),
        o => branch_target(o, d).into_iter().collect(),
    }
}

/// The first instruction of `(s, end)` — the arm of the `if` at `s`, closed
/// at `end` — that may leave the arm before its last instruction: a branch
/// to the `if` itself or to a frame around it. A branch that ends the
/// function (`return`, a branch to the function's own frame) reaches
/// nothing after the arm and is not one.
pub(crate) fn arm_branches_out(ops: &[Op<'_>], depth: &[u32], s: usize, end: usize) -> Option<usize> {
    let inner = depth[s] + 1;
    (s + 1..end).find(|&j| branch_targets(&ops[j], depth[j]).iter().any(|&t| t != 0 && t <= inner))
}

/// A branch's target depth (the frame it leaves to), or `Some(0)` for an
/// exit of the whole function; `None` for an instruction that does not
/// branch.
pub fn branch_target(op: &Op<'_>, d: u32) -> Option<u32> {
    match op {
        Op::Br { relative_depth }
        | Op::BrIf { relative_depth }
        | Op::BrOnNull { relative_depth }
        | Op::BrOnNonNull { relative_depth } => Some(d.saturating_sub(*relative_depth)),
        Op::BrTable { targets } => {
            let max = targets
                .targets()
                .filter_map(Result::ok)
                .chain(std::iter::once(targets.default()))
                .max()
                .unwrap_or(0);
            Some(d.saturating_sub(max))
        }
        Op::Return
        | Op::ReturnCall { .. }
        | Op::ReturnCallIndirect { .. }
        | Op::ReturnCallRef { .. }
        | Op::Throw { .. }
        | Op::ThrowRef
        | Op::Rethrow { .. } => Some(0),
        _ => None,
    }
}
