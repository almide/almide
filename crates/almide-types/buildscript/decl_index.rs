//! Generate `src/generated/decl_index.rs`: for every stdlib source, the names
//! of its top-level functions and the lines of its type declarations (#4458).
//!
//! The front end needs two things from EVERY bundled module, reached or not:
//! the names it declares (an auto-imported module is reached when a program
//! spells one of them, `bundled_reach`) and its type declarations (registered
//! for every program, `bundled_sigs::register_bundled_types`). Both used to
//! parse each module whole — about 600 KB of stdlib on every compile, most of
//! a small program's compile time. With this index a module is parsed whole
//! only once something reaches it; its types are parsed from a view of the
//! source that keeps only the type declarations' lines (every other line
//! blanked, so each span still points where it did).
//!
//! A text scan over the embedded (comment-blanked) source, as the other
//! tables here are. A top-level item starts on a line with no indentation; a
//! `type` item runs, with the `///` and `@` lines directly above it, up to the
//! next line that starts an item. A type declaration that holds an expression
//! (a record field's default) keeps the whole source as its view: its
//! expressions would number differently in a view. The scan is held to the
//! parser by `crates/almide-frontend/tests/decl_index_test.rs`, which parses
//! every source both ways and refuses any difference.

use std::fmt::Write as _;
use std::path::Path;

/// The function a top-level line declares, if any:
/// `[pub |local |mod ]*[effect ]fn NAME` (NAME may be `Type.method`).
fn fn_name(line: &str) -> Option<&str> {
    let mut t = line;
    loop {
        let next = ["pub ", "local ", "mod ", "effect "].iter().find_map(|p| t.strip_prefix(p));
        match next {
            Some(rest) => t = rest,
            None => break,
        }
    }
    let after = t.strip_prefix("fn ")?;
    let end = after.find(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '.')).unwrap_or(after.len());
    let name = &after[..end];
    (!name.is_empty()).then_some(name)
}

/// Does a top-level line start a `type` declaration?
fn is_type_start(line: &str) -> bool {
    let mut t = line;
    while let Some(rest) = ["pub ", "local ", "mod "].iter().find_map(|p| t.strip_prefix(p)) {
        t = rest;
    }
    t.starts_with("type ")
}

/// Does `line` start a top-level item (or the doc / attribute lines of one)?
fn starts_item(line: &str) -> bool {
    const STARTS: &[&str] = &[
        "fn ", "effect ", "local ", "mod ", "pub ", "type ", "import ", "test ", "protocol ", "let ", "var ", "@", "///",
    ];
    STARTS.iter().any(|s| line.starts_with(s))
}

/// More than one assignment `=` in a declaration: a field default (an
/// expression) besides the declaration's own `=`.
fn holds_expression(text: &str) -> bool {
    let b = text.as_bytes();
    let mut n = 0;
    for (i, &c) in b.iter().enumerate() {
        if c != b'=' {
            continue;
        }
        let prev = if i > 0 { b[i - 1] } else { b' ' };
        let next = b.get(i + 1).copied().unwrap_or(b' ');
        if matches!(prev, b'=' | b'!' | b'<' | b'>') || matches!(next, b'=' | b'>') {
            continue;
        }
        n += 1;
    }
    n > 1
}

/// One source's index: its functions, its type lines (1-based, inclusive),
/// and whether its types need the whole source.
fn index(text: &str) -> (Vec<String>, Vec<(usize, usize)>, bool) {
    let lines: Vec<&str> = text.split('\n').collect();
    let top = |l: &str| !l.is_empty() && !l.starts_with(' ') && !l.starts_with('\t');
    let mut fns = Vec::new();
    let mut ranges: Vec<(usize, usize)> = Vec::new();
    let mut whole = false;
    for (i, line) in lines.iter().enumerate() {
        if !top(line) {
            continue;
        }
        if let Some(name) = fn_name(line) {
            fns.push(name.to_string());
        }
        if !is_type_start(line) {
            continue;
        }
        let mut start = i;
        while start > 0 && (lines[start - 1].starts_with("///") || lines[start - 1].starts_with('@')) {
            start -= 1;
        }
        let mut end = i;
        let mut k = i + 1;
        while k < lines.len() && !(top(lines[k]) && starts_item(lines[k])) {
            if !lines[k].trim().is_empty() {
                end = k;
            }
            k += 1;
        }
        whole |= holds_expression(&lines[i..=end].join("\n"));
        ranges.push((start + 1, end + 1));
    }
    (fns, ranges, whole)
}

pub fn generate(sources: &[(String, String)], out_path: &Path) {
    let mut out = String::new();
    out.push_str("// @generated by crates/almide-types/build.rs (buildscript/decl_index.rs) — do not edit.\n");
    out.push_str("/// `(stem, top-level fn names, type declaration lines (1-based, inclusive), types need the whole source)`.\n");
    out.push_str("pub type DeclRow = (&'static str, &'static [&'static str], &'static [(u32, u32)], bool);\n\n");
    out.push_str("pub const DECL_INDEX: &[DeclRow] = &[\n");
    for (stem, text) in sources {
        let (fns, ranges, whole) = index(text);
        let fns: Vec<String> = fns.iter().map(|f| format!("{f:?}")).collect();
        let ranges: Vec<String> = ranges.iter().map(|(a, b)| format!("({a}, {b})")).collect();
        writeln!(out, "    ({stem:?}, &[{}], &[{}], {whole}),", fns.join(", "), ranges.join(", ")).expect("write to String");
    }
    out.push_str("];\n");
    super::in_checkout::write_if_changed(out_path, &out);
}
