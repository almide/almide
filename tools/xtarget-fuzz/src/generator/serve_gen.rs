//! Program text for the served inspection (`xtarget-fuzz inspect
//! http.serve`, driven by `oracle/serve.rs`).
//!
//! A served probe is serve-shaped (`proofs/target-availability.toml`,
//! #2659): `main` binds the port and makes one `http.serve` call, so the
//! same source runs natively, on the embedded lane and — built with
//! `almide build --target wasm` — under `wasmtime serve`. The app is a
//! top-level fn, so it is instance-closed (ADR-0020 §5.2).
//!
//! The handler (`f`) is the input the criteria vary:
//! - parity: [`synthesize_handler`], a generated handler — request readers
//!   bound first, then type-directed terms over them from the pure
//!   catalogue down to an `HttpResponse`, and in a quarter of them an
//!   `err` branch (C-367's `500 Internal error: <m>`);
//! - complexity: [`CONSTANT_APP`], whose own work is the same at every
//!   size, so what grows with the body is `http.serve`'s;
//! - alloc and diamond: [`PROBE_APP`], which reads every request reader,
//!   sets headers and takes the err path on one route.

use super::catalogue::Signature;
use super::term::{gen_expr, Builder, ScopeVar, START_FUEL};
use super::types::GenType;
use crate::rng::SplitMix64;

/// The app of the complexity probe: constant work per request.
pub const CONSTANT_APP: &str = "fn app(req: HttpRequest) -> Result[HttpResponse, String] = ok(http.response(200, \"ok\"))\n";

/// The app of the alloc and diamond probes: every reader, a header set
/// from a request header, a status outside the reason table, and an err.
/// Its Content-Type is its String body's (ADR-0032), never a header by name.
pub const PROBE_APP: &str = r#"fn app(req: HttpRequest) -> Result[HttpResponse, String] = {
  let path = http.path(req)
  let q = http.query_params(req) ?? []
  let keys = q |> list.map(((k, _)) => k) |> list.join(",")
  match path {
    "/missing" => err("no route ${path}"),
    "/a/b" => ok(http.response(200, http.body(req)) |> http.set_status(418) |> http.set_header("x-kind", "teapot")),
    _ => ok(http.with_headers(200, "${http.method(req)} ${path} [${keys}] ${http.body(req)}", [("x-token", http.header(req, "x-token") ?? "none"))])),
  }
}
"#;

/// A served program: `header` (the session plan's line), `app` and the
/// serve-shaped `main` reading the port from [`crate::oracle::serve::PORT_ENV`].
pub fn served_program(header: &str, app: &str) -> String {
    served_program_via(header, app, "http.serve", "")
}

/// [`served_program`] with `main` calling `callee` (a diamond path's
/// wrapper, `left.call`) instead of `http.serve`, after `uses` (its
/// `import self.<path>` lines).
pub fn served_program_via(header: &str, app: &str, callee: &str, uses: &str) -> String {
    let body = format!(
        "{app}\neffect fn main() -> Unit = {{\n  let port = env.get(\"{}\") ?? \"0\"\n  {callee}(int.parse(port) ?? 0, app)!\n}}\n",
        crate::oracle::serve::PORT_ENV
    );
    let imports = super::catalogue::imports_for(&format!("env.get http.serve {body}"));
    format!("{header}// generated by xtarget-fuzz (served inspection)\n{imports}{uses}\n{body}")
}

/// The diamond's three projects, one per path (`d`: `http.serve` itself,
/// `l` / `r`: through `left.call` / `right.call`, each a wrapper over
/// `base.call`, which calls `http.serve`): a path never returns until the
/// SIGTERM, so each runs alone and is driven by the same session.
pub fn diamond_projects(header: &str, app: &str) -> Vec<super::Project> {
    let sig = "pub effect fn call(port: Int, f: effect (HttpRequest) -> HttpResponse) -> Unit";
    let base = format!("import http\n\n{sig} = http.serve(port, f)!\n");
    let path = format!("import http\nimport self.base\n\n{sig} = base.call(port, f)!\n");
    ["d", "l", "r"]
        .into_iter()
        .map(|p| {
            let main = match p {
                "d" => served_program(header, app),
                "l" => served_program_via(header, app, "left.call", "import self.left\n"),
                _ => served_program_via(header, app, "right.call", "import self.right\n"),
            };
            super::Project {
                files: vec![
                    ("app/almide.toml".to_string(), "[package]\nname = \"app\"\nversion = \"0.1.0\"\n".to_string()),
                    ("app/src/base.almd".to_string(), base.clone()),
                    ("app/src/left.almd".to_string(), path.clone()),
                    ("app/src/right.almd".to_string(), path.clone()),
                    ("app/src/main.almd".to_string(), main),
                ],
                entry: "app/src/main.almd".to_string(),
            }
        })
        .collect()
}

/// The request readers a generated handler starts from: each is bound
/// with probability 1/2, so a handler reads a different subset.
const READERS: &[(&str, &str, fn() -> GenType)] = &[
    ("method", "http.method(req)", || GenType::String),
    ("path", "http.path(req)", || GenType::String),
    ("body", "http.body(req)", || GenType::String),
    ("token", "http.header(req, \"x-token\") ?? \"none\"", || GenType::String),
    ("ctype", "http.header(req, \"Content-Type\") ?? \"\"", || GenType::String),
    ("query", "http.query_params(req) ?? []", || GenType::List(Box::new(GenType::Tuple2(Box::new(GenType::String), Box::new(GenType::String))))),
];

/// Goal types of the extra bindings a handler computes before its answer.
fn extra_goal(rng: &mut SplitMix64) -> GenType {
    match rng.below(5) {
        0 => GenType::Int,
        1 => GenType::Bool,
        2 => GenType::List(Box::new(GenType::String)),
        _ => GenType::String,
    }
}

/// The catalogue a handler draws from: pure functions only. A handler's
/// effects are other functions' inspections (and a stock export refuses a
/// handler that reads files, C-375); a leg-dependent encoding or a
/// host-decided value would differ by contract, not by defect.
/// A host module's functions stay out even when declared pure: their
/// arguments are built from the fixtures (`net.tcp_is_open` over a
/// connection to the echo fixture), which only a socket host can reach.
pub fn handler_catalogue(catalogue: &[Signature]) -> Vec<Signature> {
    const HOST_MODULES: &[&str] = &["net", "process", "fs", "env", "io", "args", "random"];
    catalogue
        .iter()
        .filter(|s| !s.effect && s.observed_through.is_none() && s.verdict.is_none() && !HOST_MODULES.contains(&s.module))
        .cloned()
        .collect()
}

/// Status codes a handler answers with most of the time: in the reason
/// table and out of it, the bodyless ones (1xx, 204, 304) and a redirect.
/// The rest of the time the status is a generated Int, whatever it is: the
/// handler's domain is every `HttpResponse` the stdlib can build.
const STATUSES: &[i64] = &[200, 201, 204, 301, 304, 400, 404, 418, 422, 299, 500, 503, 599, 103];

/// Header names a `set_header` uses most of the time (tokens, in mixed
/// case, one a host manages); the rest of the time a generated String.
const HEADER_NAMES: &[&str] = &["x-a", "X-Token", "content-type", "Cache-Control", "x-é-not-token", "Content-Length"];

/// The response: a catalogue-directed term (a third of the time), or
/// `http.response` / `http.with_headers` over a status and terms of the
/// handler's scope (the request readers), then up to two `set_header` /
/// `set_status` steps.
fn gen_response(b: &mut Builder) -> String {
    let status = |b: &mut Builder| -> String {
        if b.rng.chance(1, 4) {
            b.fuel = START_FUEL;
            gen_expr(b, &GenType::Int)
        } else {
            b.rng.pick(STATUSES).to_string()
        }
    };
    let mut resp = match b.rng.below(3) {
        0 => {
            b.fuel = START_FUEL;
            gen_expr(b, &GenType::Nominal("HttpResponse"))
        }
        1 => {
            let s = status(b);
            b.fuel = START_FUEL;
            let body = gen_expr(b, &GenType::String);
            format!("http.response({s}, {body})")
        }
        _ => {
            let s = status(b);
            b.fuel = START_FUEL;
            let body = gen_expr(b, &GenType::String);
            b.fuel = START_FUEL;
            let headers = gen_expr(b, &GenType::List(Box::new(GenType::Tuple2(Box::new(GenType::String), Box::new(GenType::String)))));
            format!("http.with_headers({s}, {body}, {headers})")
        }
    };
    for _ in 0..b.rng.below(3) {
        if b.rng.chance(1, 4) {
            let s = status(b);
            resp = format!("http.set_status({resp}, {s})");
            continue;
        }
        let name = if b.rng.chance(3, 4) {
            format!("\"{}\"", b.rng.pick(HEADER_NAMES))
        } else {
            b.fuel = START_FUEL;
            gen_expr(b, &GenType::String)
        };
        b.fuel = START_FUEL;
        let value = gen_expr(b, &GenType::String);
        resp = format!("http.set_header({resp}, {name}, {value})");
    }
    resp
}

/// A generated handler: `fn app(req: HttpRequest) -> Result[HttpResponse, String]`.
pub fn synthesize_handler(rng: &mut SplitMix64, catalogue: &[Signature]) -> String {
    let mut b = Builder {
        rng,
        catalogue,
        scope: vec![ScopeVar { name: "req".into(), ty: GenType::Nominal("HttpRequest") }],
        stmts: Vec::new(),
        fuel: 0,
        fresh: 0,
        effect: false,
    };
    for (name, expr, ty) in READERS {
        if b.rng.chance(1, 2) {
            let ty = ty();
            b.stmts.push(format!("let {name}: {} = {expr}", ty.render()));
            b.scope.push(ScopeVar { name: (*name).into(), ty });
        }
    }
    for _ in 0..b.rng.below(3) {
        let goal = extra_goal(b.rng);
        b.fuel = START_FUEL;
        let e = gen_expr(&mut b, &goal);
        let name = format!("x{}", b.fresh);
        b.fresh += 1;
        b.stmts.push(format!("let {name}: {} = {e}", goal.render()));
        b.scope.push(ScopeVar { name, ty: goal });
    }
    let resp = gen_response(&mut b);
    b.stmts.push(format!("let resp: HttpResponse = {resp}"));
    let tail = if b.rng.chance(1, 4) {
        b.fuel = START_FUEL;
        let cond = gen_expr(&mut b, &GenType::Bool);
        b.fuel = START_FUEL;
        let msg = gen_expr(&mut b, &GenType::String);
        format!("if {cond} then err({msg}) else ok(resp)")
    } else {
        "ok(resp)".to_string()
    };
    let mut src = String::from("fn app(req: HttpRequest) -> Result[HttpResponse, String] = {\n");
    for s in &b.stmts {
        src.push_str("  ");
        src.push_str(s);
        src.push('\n');
    }
    src.push_str("  ");
    src.push_str(&tail);
    src.push_str("\n}\n");
    src
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::oracle::serve::{plan_of, Plan};

    #[test]
    fn a_served_program_is_serve_shaped_and_carries_its_plan() {
        let src = served_program(&Plan::Sized { k: 4, n: 64 }.header(), CONSTANT_APP);
        assert_eq!(plan_of(&src), Some(Plan::Sized { k: 4, n: 64 }));
        assert!(src.contains("import env\n") && src.contains("import http\n"), "{src}");
        assert!(src.ends_with("effect fn main() -> Unit = {\n  let port = env.get(\"XF_SERVE_PORT\") ?? \"0\"\n  http.serve(int.parse(port) ?? 0, app)!\n}\n"), "{src}");
    }

    #[test]
    fn each_diamond_path_reaches_serve_through_its_own_wrapper() {
        let ps = diamond_projects(&Plan::Script.header(), PROBE_APP);
        assert_eq!(ps.len(), 3);
        let main = |i: usize| ps[i].files.iter().find(|(p, _)| p == "app/src/main.almd").unwrap().1.clone();
        assert!(main(0).contains("  http.serve(int.parse(port) ?? 0, app)!\n"));
        assert!(main(1).contains("import self.left\n") && main(1).contains("  left.call(int.parse(port) ?? 0, app)!\n"));
        assert!(main(2).contains("import self.right\n") && main(2).contains("  right.call(int.parse(port) ?? 0, app)!\n"));
        for i in 0..3 {
            assert_eq!(plan_of(&main(i)), Some(Plan::Script));
        }
    }

    #[test]
    fn generated_handlers_are_deterministic_pure_and_answer_a_response() {
        let all = super::super::build_catalogue();
        let cat = handler_catalogue(&all);
        assert!(cat.iter().all(|s| !s.effect));
        assert!(cat.iter().any(|s| s.module == "http" && s.func == "with_headers"), "the response builders are pure and drawn");
        let gen = |seed| synthesize_handler(&mut SplitMix64::for_program(7, seed), &cat);
        assert_eq!(gen(3), gen(3));
        let many: Vec<String> = (0..400).map(gen).collect();
        // A pure handler reaches no effect, not even through a nominal's
        // template (the fixture address is read with `env.get`).
        for h in &many {
            assert!(!h.contains("env.") && !h.contains("http.start(") && !h.contains("net."), "an effect in a pure handler:\n{h}");
        }
        assert!(many.iter().all(|h| h.starts_with("fn app(req: HttpRequest) -> Result[HttpResponse, String] = {\n") && h.contains("  let resp: HttpResponse = ")));
        assert!(many.iter().any(|h| h.contains(" then err(")), "some handlers take the err path");
        assert!(many.iter().any(|h| h.contains("http.body(req)")), "handlers read the request");
    }
}
