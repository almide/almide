#!/usr/bin/env bash
# The compile-cost budget measurement (ADR-0030 D6, #4136).
#
# Each budget's default is set at about ten times the largest figure real
# code reaches, so model-written code never meets one and only adversarial
# input does. This script measures that figure: it runs
# `almide check --budget-report` on every `.almd` under spec/, stdlib/ and
# the exercises corpus (research/benchmark/exercises), takes the maximum each
# budget OBSERVED over all of them, and writes proofs/compile-budgets.toml:
#
#   [type_size]
#   observed_max = 412        # the largest figure over the corpus
#   observed_in = "spec/…"    # where it was reached
#   default = 4096            # the budget in force (crates/almide-base/src/budget.rs)
#   headroom = 9.9            # default / observed_max
#
# A file that does not check still reports what it observed before it
# stopped, so it counts. The project-side budgets (manifest_bytes,
# dependency_count, dependency_depth) are measured over the corpus's
# almide.toml files the same way, through `almide check` run in each
# project directory.
#
#   ALMIDE_BIN=target/release/almide bash scripts/measure-compile-budgets.sh [--check]
#
# --check: recompute and fail if a default is under 2x its observed maximum
# (the corpus outgrew a budget) — the measurement is then due again.
set -uo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.." || exit 2
BIN="${ALMIDE_BIN:-target/release/almide}"
[ -x "$BIN" ] || { echo "::error::ALMIDE_BIN not executable: $BIN"; exit 2; }
OUT=proofs/compile-budgets.toml
mode="${1:-write}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# One `budget <name> observed=<n> …` line per budget per file, tagged with the file.
measure() {
  local f="$1" dir="${2:-}"
  if [ -n "$dir" ]; then
    (cd "$dir" && timeout 120 "$OLDPWD/$BIN" check --budget-report 2>&1 >/dev/null) | grep '^budget ' | sed "s|^|$dir |"
  else
    timeout 120 "$BIN" check "$f" --budget-report 2>&1 >/dev/null | grep '^budget ' | sed "s|^|$f |"
  fi
}

git ls-files 'spec/*.almd' 'stdlib/*.almd' 'research/benchmark/exercises/*.almd' > "$tmp/files"
n=0
while IFS= read -r f; do
  measure "$f" >> "$tmp/rows"
  n=$((n + 1))
done < "$tmp/files"
git ls-files '*almide.toml' | grep -vE '^(tests/|docs/)' | while IFS= read -r m; do
  measure "" "$(dirname "$m")" >> "$tmp/rows"
done

# file budget name observed=N work=W limit=L → per name: max N and its file.
awk '
  { split($4, o, "="); split($6, l, "="); name = $3; v = o[2] + 0
    if (!(name in max) || v > max[name]) { max[name] = v; where[name] = $1 }
    lim[name] = l[2] }
  END { for (k in max) printf "%s %d %s %d\n", k, max[k], where[k], lim[k] }
' "$tmp/rows" | sort > "$tmp/max"

if [ "$mode" = "--check" ]; then
  fail=0
  while read -r name obs where lim; do
    if [ "$obs" -gt 0 ] && [ $((lim)) -lt $((obs * 2)) ]; then
      echo "::error::budget $name: default $lim is under 2x the corpus maximum $obs (in $where) — re-run scripts/measure-compile-budgets.sh and reset the default"
      fail=1
    fi
  done < "$tmp/max"
  exit $fail
fi

{
  echo "# Compile-cost budgets against the corpus (ADR-0030 D6) — generated by"
  echo "# scripts/measure-compile-budgets.sh over $n files (spec/, stdlib/, research/benchmark/exercises)"
  echo "# and the corpus's almide.toml projects. Each default is about 10x observed_max."
  while read -r name obs where lim; do
    echo
    echo "[$name]"
    echo "observed_max = $obs"
    echo "observed_in = \"$where\""
    echo "default = $lim"
    if [ "$obs" -gt 0 ]; then
      awk -v l="$lim" -v o="$obs" 'BEGIN { printf "headroom = %.1f\n", l / o }'
    fi
  done < "$tmp/max"
} > "$OUT"
echo "wrote $OUT"
