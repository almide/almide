#!/usr/bin/env bash
# gen-almide-packages.sh — regenerate src/almide_packages.txt, the snapshot of
# the Almide packages published under github.com/almide (#4093).
#
# The compiler embeds the snapshot for two jobs only, both offline and
# deterministic:
#   - resolving a one-part `almide add <name>` to its repository, because a
#     package's name and its repository's name differ (`bindgen` lives in
#     `almide/almide-bindgen`);
#   - the "did you mean" line on a refused or not-found `almide add`.
# It is not an allowlist: trust is `[trust] owners` in each project's
# almide.toml, and github.com/almide is trusted whether or not a package is
# listed here.
#
# A package is a public, unarchived repository whose root almide.toml has a
# `[package] name`. Output: one `<package-name> <repository>` per line,
# sorted. Needs `gh` (authenticated) and network; run it by hand when the
# org gains or renames a package, and commit the result.
set -euo pipefail
export LC_ALL=C
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/src/almide_packages.txt"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "# Packages under github.com/almide: <package-name> <repository>."
  echo "# Generated by scripts/gen-almide-packages.sh; do not edit by hand."
} > "$tmp"

gh repo list almide --limit 1000 --json name,visibility,isArchived \
  --jq '.[] | select(.visibility == "PUBLIC" and (.isArchived | not)) | .name' |
  sort |
  while read -r repo; do
    manifest="$(gh api "repos/almide/$repo/contents/almide.toml" --jq .content 2>/dev/null | base64 -d 2>/dev/null || true)"
    [ -n "$manifest" ] || continue
    name="$(printf '%s\n' "$manifest" | awk -F'"' '/^\[package\]/ { p = 1; next } /^\[/ { p = 0 } p && /^name *=/ { print $2; exit }')"
    [ -n "$name" ] || continue
    echo "$name $repo"
  done | sort >> "$tmp"

lines=$(grep -vc '^#' "$tmp" || true)
if [ "$lines" -eq 0 ]; then
  echo "gen-almide-packages: found no packages (gh not authenticated or offline?); $OUT left unchanged" >&2
  exit 1
fi
mv "$tmp" "$OUT"
trap - EXIT
echo "gen-almide-packages: $lines packages -> $OUT"
