//! A Bytes value read through `!` over a match that rebuilds its Result,
//! at a runtime `&Vec<u8>` slot, builds on the Rust target (#4784).
//!
//! `bytes.to_list((match unix.shm_read(o1, 0, 2) { ok(b) => ok(b), err(e) =>
//! … })!)` inside a fallible `list.map` rendered `&((match …)?)`: rustc
//! read the `?` operand at the slot's `Vec<u8>` while the arms built
//! `AlmideRcCow<Vec<u8>>` (E0308, "`?` operator has incompatible types"),
//! on a program `almide check` accepts. The borrow now derefs explicitly
//! (`&*(…)`), as it does for a bare propagating match (#1210). Found by the
//! stdlib re-inspection's parity campaign for `unix.select`; the generator's
//! program is kept whole, since smaller forms built.

use std::io::Write;
use std::path::Path;
use std::process::Command;

fn almide_bin() -> String {
    if let Ok(bin) = std::env::var("ALMIDE_BIN") {
        return bin;
    }
    let cargo_bin = Path::new(env!("CARGO_MANIFEST_DIR")).join("target/release/almide");
    if cargo_bin.exists() {
        return cargo_bin.to_str().unwrap().to_string();
    }
    "almide".to_string()
}

const PROGRAM: &str = r#"// generated by xtarget-fuzz (type-directed synthesis)
import hash
import env
import io
import unix

effect fn main() -> Unit = {
  let x1: Result[List[Fd], String] = unix.select(
    [
      (match unix.connect((env.get("XF_UNIX_SINK") ?? "")) {
        ok(okv) => okv,
        err(e) => panic(e),
      }),
      {
        let ul = (match unix.listen("u0.sock") {
          ok(okv) => okv,
          err(e) => panic(e),
        })
        let uc = (match unix.connect("u0.sock") {
          ok(okv) => okv,
          err(e) => panic(e),
        })
        let us = (match unix.accept(ul) {
          ok(okv) => okv,
          err(e) => panic(e),
        })
        let _uw: Result[Unit, String] = unix.write_fds(
          uc,
          bytes.from_string("hello world"),
          [
            (match unix.shm_create(8) {
              ok(okv) => okv,
              err(e) => panic(e),
            })
          ],
        )
        let _ux: Result[Unit, String] = io.close(uc)
        let _uy: Result[Unit, String] = io.close(ul)
        us
      }
    ],
    int.abs(hash.adler32(bytes.from_list([]))) % 50,
  )
  let r2: Result[List[Fd], String] = x1
  let y3: Set[Bool] = set.new()
  let r7: (Bool, Float) = string.fold(
    (if option.is_some(set.min_by(y3, ((tmp4) => 42))) then "a\tb\nc" else "Привет"),
    (false, 0.3),
    ((s5, tmp6) => s5),
  )
  let r8: String = string.repeat("ß", 2)
  let r2_o: Result[List[List[Int]], String] = match r2 {
    ok(o0) => ok(list.map(
      o0,
      (o1) => bytes.to_list((match unix.shm_read(o1, 0, 2) {
        ok(b) => ok(b),
        err(e) => if string.contains(e, "Illegal seek") then ok(bytes.new()) else err(e),
      })!),
    )!),
    err(e0) => err(e0),
  }
  println("r8 = ${r8}")
}
"#;

#[test]
fn a_bang_over_a_rebuilt_bytes_result_match_builds_native() {
    let dir = std::env::temp_dir().join(format!("almd_4784_{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("main.almd");
    std::fs::File::create(&file).unwrap().write_all(PROGRAM.as_bytes()).unwrap();
    let out = Command::new(almide_bin())
        .args(["build", file.to_str().unwrap(), "-o", dir.join("bin").to_str().unwrap()])
        .output()
        .expect("failed to spawn almide");
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    std::fs::remove_dir_all(&dir).ok();
    assert!(out.status.success(), "the native build failed:
{stderr}");
}
